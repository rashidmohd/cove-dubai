/**
 * The admin panel's icon set.
 *
 * Inline SVG, hand-copied from Lucide (ISC licence) rather than installed: six
 * nav glyphs and a dozen UI marks do not justify a dependency, and inlining
 * means they inherit `currentColor` and ship no extra request.
 *
 * Every icon is decorative — it always sits beside a text label, never alone as
 * the only meaning. So they are `aria-hidden` by default and contribute nothing
 * to the accessible name, which comes from the words next to them.
 *
 * Icons are **not** used on guest-facing surfaces. The brand there is
 * typographic (`cove-design-system`); this set exists because a dense work tool
 * needs scannable targets in a way a marketing page does not.
 */
import type { SVGProps } from 'react';

type IconProps = Omit<SVGProps<SVGSVGElement>, 'children'> & {
  /** Edge length in `rem`-relative units. Defaults to 1rem — Lucide's 16px. */
  size?: string;
};

function Icon({
  size = '1rem',
  children,
  ...rest
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  );
}

